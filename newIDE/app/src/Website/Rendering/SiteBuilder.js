export const buildWebsiteFiles = (
  project: WebsiteProject,
  runtime: RuntimeSources
): BuildResult => {
  const issues = [];
  const files = [];
  const usedAssetIds = new Set();
  const resolveAssetUrlFrom = (prefix: string) => (assetId: string) => {
    const path = getAssetExportPath(project, assetId);
    if (!path) return '';
    usedAssetIds.add(assetId);
    return prefix + path;
  };
  const getPageHref = (page: WebsitePage) => getPageFileName(page);

  files.push({ path: 'css/webvelop.css', content: runtime.runtimeCss });
  files.push({ path: 'js/webvelop-runtime.js', content: runtime.runtimeJs });
  files.push({ path: 'css/site.css', content: generateSiteCss(project, resolveAssetUrlFrom('../')) });
  files.push({ path: 'js/site.js', content: generateSiteScript(project, issues, getPageHref) });

  let usesReact = false;
  const faviconUrl = project.settings.faviconAssetId
    ? resolveAssetUrlFrom('')(project.settings.faviconAssetId)
    : null;

  project.pages.forEach(page => {
    const { context, html } = renderPageBody(project, page, 'export', resolveAssetUrlFrom(''), getPageHref);
    addRenderWarnings(issues, context, page);
    const pageReact = context.usedReactComponentIds.size > 0;
    if (pageReact) usesReact = true;
    const baseName = getPageFileName(page).replace(/\.html$/, '');
    files.push({
      path: `css/page-${baseName}.css`,
      content: GENERATED_HEADER + '\n' + generateTreeCss(page.root, resolveAssetUrlFrom('../'), page.css),
    });
    files.push({
      path: `js/page-${baseName}.js`,
      content: generatePageScript(project, page, context, issues, 'export'),
    });
    files.push({
      path: getPageFileName(page),
      content: generatePageHtml({
        project,
        page,
        bodyHtml: html,
        faviconUrl,
        styles: [
          { href: 'css/webvelop.css' },
          { href: 'css/site.css' },
          { href: `css/page-${baseName}.css` },
        ],
        scripts: [
          ...(pageReact
            ? [{ src: 'vendor/react.production.min.js' }, { src: 'vendor/react-dom.production.min.js' }]
            : []),
          { src: 'js/webvelop-runtime.js' },
          { src: 'js/site.js' },
          { src: `js/page-${baseName}.js` },
        ],
      }),
    });
  });

  if (usesReact) {
    files.push({ path: 'vendor/react.production.min.js', content: runtime.reactJs });
    files.push({ path: 'vendor/react-dom.production.min.js', content: runtime.reactDomJs });
  }
  usedAssetIds.forEach(assetId => {
    files.push({ path: getAssetExportPath(project, assetId), assetId });
  });
  // Also export assets not referenced by elements (they may be used from scripts).
  project.assets.forEach(asset => {
    if (!usedAssetIds.has(asset.id)) files.push({ path: getAssetExportPath(project, asset.id), assetId: asset.id });
  });
  if (!project.pages.length) {
    issues.push({ severity: 'error', source: 'Website', message: 'The website has no page.' });
  }
  return { files, issues };
};

