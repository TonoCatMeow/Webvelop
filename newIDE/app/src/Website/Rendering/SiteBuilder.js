export type CanvasContent = {|
  css: string,
  html: string,
  reactCode: string,
  usesReact: boolean,
  warnings: Array<string>,
|};

export const buildCanvasContent = (
  project: WebsiteProject,
  ref: DocumentRef,
  resolveAssetUrl: (assetId: string) => string
): ?CanvasContent => {
  const document = getDocument(project, ref);
  if (!document) return null;
  const getPageHref = () => '#';
  const context = createRenderContext(project, { mode: 'editor', resolveAssetUrl, getPageHref });
  let html;
  if (ref.kind === 'component') {
    // $FlowFixMe[prop-missing]
    const component: any = document;
    html = `<div class="wv-page wv-component-canvas">${renderTree(component.root, context, {
      propsValues: getComponentDefaultPropsValues(component),
      componentId: component.id,
    })}</div>`;
  } else {
    html = renderTree(document.root, context);
  }
  const css = [
    generateSiteCss(project, resolveAssetUrl),
    generateTreeCss(document.root, resolveAssetUrl, ref.kind === 'page' ? (document: any).css : ''),
  ].join('\n');
  const issues = [];
  const reactCode = project.reactComponents
    .filter(reactComponent => context.usedReactComponentIds.has(reactComponent.id))
    .map(reactComponent => {
      const compiled = compileReactComponent(reactComponent);
      compiled.errors.forEach(error => issues.push(error.message));
      return compiled.registrationCode;
    })
    .join('\n');
  return {
    css,
    html,
    reactCode,
    usesReact: context.usedReactComponentIds.size > 0,
    warnings: [...context.warnings, ...issues],
  };
};
