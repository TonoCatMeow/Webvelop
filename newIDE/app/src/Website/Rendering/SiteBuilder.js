// Preview (self-contained pages, navigation handled by the editor)
// ---------------------------------------------------------------------------

export const buildStandalonePage = (
  project: WebsiteProject,
  pageId: string,
  runtime: RuntimeSources,
  resolveAssetUrl: (assetId: string) => string,
  mode: 'preview' | 'export' = 'preview'
): {| html: string, issues: Array<BuildIssue> |} => {
  const issues = [];
  const page = project.pages.find(p => p.id === pageId) || project.pages[0];
  if (!page) return { html: '<!DOCTYPE html><p>No page.</p>', issues };
  const getPageHref = (target: WebsitePage) => getPageFileName(target);
  const { context, html } = renderPageBody(project, page, mode === 'preview' ? 'preview' : 'export', resolveAssetUrl, getPageHref);
  addRenderWarnings(issues, context, page);
  const usesReact = context.usedReactComponentIds.size > 0;
  const faviconUrl = project.settings.faviconAssetId ? resolveAssetUrl(project.settings.faviconAssetId) : null;
  return {
    html: generatePageHtml({
      project,
      page,
      bodyHtml: html,
      faviconUrl,
      styles: [
        { inline: runtime.runtimeCss },
        { inline: generateSiteCss(project, resolveAssetUrl) },
        { inline: generateTreeCss(page.root, resolveAssetUrl, page.css) },
      ],
      scripts: [
        ...(usesReact ? [{ inline: runtime.reactJs }, { inline: runtime.reactDomJs }] : []),
        { inline: runtime.runtimeJs },
        { inline: generateSiteScript(project, issues, getPageHref) },
        { inline: generatePageScript(project, page, context, issues, mode === 'preview' ? 'preview' : 'export') },
      ],
    }),
    issues,
  };
};

/** Check the whole project for errors (used by the "Problems" panel and before exports). */
export const checkProject = (project: WebsiteProject): Array<BuildIssue> => {
  const issues = [];
  const getPageHref = (page: WebsitePage) => getPageFileName(page);
  generateSiteScript(project, issues, getPageHref);
  project.pages.forEach(page => {
    const { context } = renderPageBody(project, page, 'export', () => '', getPageHref);
    addRenderWarnings(issues, context, page);
    generatePageScript(project, page, context, issues, 'export');
  });
  return issues;
};

