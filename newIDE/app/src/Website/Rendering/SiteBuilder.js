export type RuntimeSources = {|
  runtimeJs: string,
  runtimeCss: string,
  reactJs: string,
  reactDomJs: string,
|};

export type BuildIssue = {|
  severity: 'error' | 'warning',
  source: string,
  message: string,
  line?: ?number,
  column?: ?number,
  /** What to open in the editor to fix the issue. */
  location?: ?{| kind: string, id: string |},
|};

export type BuiltFile = {|
  path: string,
  /** Text content of the file. */
  content?: string,
  /** For assets: the id of the asset to copy. */
  assetId?: string,
|};

export type BuildResult = {|
  files: Array<BuiltFile>,
  issues: Array<BuildIssue>,
|};

const GENERATED_HEADER = '/* Generated by Webvelop - https://webvelop.local */';

/** Make a JSON safe to be inlined in a <script> tag. */
export const toScriptJson = (value: any): string =>
  JSON.stringify(value)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');

const inlineScriptSafe = (code: string): string => code.replace(/<\/script/gi, '<\\/script');
const inlineStyleSafe = (css: string): string => css.replace(/<\/style/gi, '<\\/style');

export const getAssetExportPath = (project: WebsiteProject, assetId: string): string => {
  const asset = project.assets.find(a => a.id === assetId);
  if (!asset) return '';
  const extensionMatch = asset.name.match(/\.([a-zA-Z0-9]+)$/);
  const extension = extensionMatch ? extensionMatch[1].toLowerCase() : 'bin';
  const baseName = slugify(asset.name.replace(/\.[^.]+$/, '')) || 'asset';
  // Keep names readable, but unique.
  const sameName = project.assets.filter(
    a => slugify(a.name.replace(/\.[^.]+$/, '')) === baseName && a.id !== asset.id
  );
  return `assets/${sameName.length ? baseName + '-' + asset.id : baseName}.${extension}`;
};

