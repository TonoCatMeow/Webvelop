export const generateSiteCss = (
  project: WebsiteProject,
  resolveAssetUrl: (assetId: string) => string
): string => {
  const parts = [GENERATED_HEADER, generateThemeCss(project, resolveAssetUrl)];
  parts.push(generateStyleClassesCss(project, resolveAssetUrl));
  // Components (shared by all pages).
  const componentChunks = emptyChunks();
  project.components.forEach(component => {
    addElementTreeRules(componentChunks, component.root, resolveAssetUrl);
  });
  parts.push(chunksToCss(componentChunks));
  project.reactComponents.forEach(reactComponent => {
    if (reactComponent.css && reactComponent.css.trim())
      parts.push(`/* React component ${reactComponent.name} */\n${reactComponent.css}`);
  });
  if (project.settings.globalCss && project.settings.globalCss.trim())
    parts.push(`/* Global CSS */\n${project.settings.globalCss}`);
  return parts.filter(Boolean).join('\n');
};

/** CSS of the elements of a page or component tree (and of the component instances it contains). */
export const generateTreeCss = (
  root: any,
  resolveAssetUrl: (assetId: string) => string,
  extraCss: string = ''
): string => {
  const chunks = emptyChunks();
  addElementTreeRules(chunks, root, resolveAssetUrl);
  // Instance elements style the root of the component they render.
  walkElements(root, element => {
    if (element.type === 'component') {
      addStylesRules(chunks, '.wv-' + element.id + '.wv-' + element.id, element.styles || {}, resolveAssetUrl, null);
    }
  });
  return chunksToCss(chunks) + (extraCss && extraCss.trim() ? `\n/* Page CSS */\n${extraCss}` : '');
};

