const ATTRIBUTE_NAMES = {
  class: 'className',
  for: 'htmlFor',
  tabindex: 'tabIndex',
  readonly: 'readOnly',
  maxlength: 'maxLength',
  minlength: 'minLength',
  autoplay: 'autoPlay',
  playsinline: 'playsInline',
  allowfullscreen: 'allowFullScreen',
  novalidate: 'noValidate',
  colspan: 'colSpan',
  rowspan: 'rowSpan',
  srcset: 'srcSet',
  crossorigin: 'crossOrigin',
  frameborder: 'frameBorder',
  viewbox: 'viewBox',
  enctype: 'encType',
  autocomplete: 'autoComplete',
  spellcheck: 'spellCheck',
  contenteditable: 'contentEditable',
};
const VOID_ELEMENTS = ['img', 'input', 'br', 'hr', 'meta', 'link', 'source', 'area', 'col', 'embed', 'track', 'wbr'];
const BOOLEAN_ATTRIBUTES = ['required', 'disabled', 'checked', 'muted', 'loop', 'controls', 'autoplay', 'playsinline', 'allowfullscreen', 'novalidate', 'readonly', 'multiple', 'selected', 'hidden'];

const toJsxAttributeName = (name: string): string => {
  if (ATTRIBUTE_NAMES[name]) return ATTRIBUTE_NAMES[name];
  if (name.startsWith('data-') || name.startsWith('aria-')) return name;
  return name.replace(/[-:]([a-z])/g, (match, letter) => letter.toUpperCase());
};

const styleToObject = (style: string): string => {
  const entries = style
    .split(';')
    .map(part => part.trim())
    .filter(Boolean)
    .map(part => {
      const index = part.indexOf(':');
      const property = part.substring(0, index).trim();
      const value = part.substring(index + 1).trim();
      const key = property.startsWith('--') ? JSON.stringify(property) : property.replace(/-([a-z])/g, (m, l) => l.toUpperCase());
      return `${key}: ${JSON.stringify(value)}`;
    });
  return `{{ ${entries.join(', ')} }}`;
};

const indentation = (depth: number) => '  '.repeat(depth);

/** Convert an HTML string (as generated by the renderer) to JSX. */
export const htmlToJsx = (
  html: string,
  usedComponents: Set<string>,
  baseDepth: number = 2
): string => {
  const parser = new DOMParser();
  const document = parser.parseFromString(`<!DOCTYPE html><body>${html}</body>`, 'text/html');
  const convert = (node: any, depth: number): string => {
    if (node.nodeType === 3) {
      const text = node.textContent;
      if (!text.trim()) return '';
      return indentation(depth) + (/[{}<>&]/.test(text) || /^\s|\s$/.test(text) ? `{${JSON.stringify(text)}}` : text);
    }
    if (node.nodeType !== 1) return '';
    const tag = node.namespaceURI === 'http://www.w3.org/2000/svg' ? node.localName : node.tagName.toLowerCase();
    const attributes = [];
    let innerHtml = null;
    let reactComponent = null;
    Array.from(node.attributes).forEach((attribute: any) => {
      const name = attribute.name;
      const value = attribute.value;
      if (name === 'data-wv-react') {
        reactComponent = value;
        return;
      }
      if (name === 'data-wv-props') return;
      if (name === 'style') {
        attributes.push(`style=${styleToObject(value)}`);
        return;
      }
      let jsxName = toJsxAttributeName(name);
      if (tag === 'input' && name === 'value') jsxName = 'defaultValue';
      if (tag === 'input' && name === 'checked') jsxName = 'defaultChecked';
      if (BOOLEAN_ATTRIBUTES.includes(name) && (value === '' || value === name)) {
        attributes.push(jsxName);
        return;
      }
      // JSX string attributes have no escape sequences: use an expression when needed.
      attributes.push(/["\\\n]/.test(value) ? `${jsxName}={${JSON.stringify(value)}}` : `${jsxName}="${value}"`);
    });
    if (node.classList && node.classList.contains('wv-embed')) {
      innerHtml = node.innerHTML;
    }
    const attributesText = attributes.length ? ' ' + attributes.join(' ') : '';
    if (reactComponent) {
      usedComponents.add(reactComponent);
      let props = '{}';
      try {
        props = JSON.stringify(JSON.parse(node.getAttribute('data-wv-props') || '{}'));
      } catch (e) {}
      return `${indentation(depth)}<${tag}${attributesText}>\n${indentation(depth + 1)}<${reactComponent} {...${props}} />\n${indentation(depth)}</${tag}>`;
    }
    if (innerHtml !== null) {
      return `${indentation(depth)}<${tag}${attributesText} dangerouslySetInnerHTML={{ __html: ${JSON.stringify(innerHtml)} }} />`;
    }
    if (tag === 'textarea') {
      const text = node.textContent;
      return `${indentation(depth)}<textarea${attributesText}${text ? ` defaultValue=${JSON.stringify(text)}` : ''} />`;
    }
    if (VOID_ELEMENTS.includes(tag)) return `${indentation(depth)}<${tag}${attributesText} />`;
    const children = Array.from(node.childNodes)
      .map(child => convert(child, depth + 1))
      .filter(Boolean);
    if (!children.length) return `${indentation(depth)}<${tag}${attributesText} />`;
    return `${indentation(depth)}<${tag}${attributesText}>\n${children.join('\n')}\n${indentation(depth)}</${tag}>`;
  };
  return Array.from(document.body.childNodes)
    .map(node => convert(node, baseDepth))
    .filter(Boolean)
    .join('\n');
};

const REACT_IMPORT =
  "import React, { useState, useEffect, useLayoutEffect, useRef, useMemo, useCallback, useReducer, useContext, useId, createContext, Fragment, Children, cloneElement } from 'react';";

export const buildReactProjectFiles = (
  project: WebsiteProject,
  runtime: RuntimeSources
): {| files: Array<BuiltFile>, issues: Array<BuildIssue> |} => {
  const issues = [];
  const files = [];
  const usedAssetIds = new Set();
  const resolveAssetUrlFrom = (prefix: string) => (assetId: string) => {
    const path = getAssetExportPath(project, assetId);
    if (!path) return '';
    usedAssetIds.add(assetId);
    return prefix + path;
  };
  const getPageHref = (page: WebsitePage) => getPageFileName(page);
  const packageName = slugify(project.name) || 'website';
  const pageEntries = [];

  // Runtime and shared code.
  files.push({ path: 'src/webvelop/webvelop.css', content: runtime.runtimeCss });
  files.push({
    path: 'src/webvelop/react-global.js',
    content: `// The Webvelop runtime uses React from the global scope (for Webvelop.useVariable).\nimport React from 'react';\nwindow.React = React;\n`,
  });
  files.push({ path: 'src/webvelop/webvelop-runtime.js', content: runtime.runtimeJs });
  files.push({
    path: 'src/webvelop/site-config.js',
    content: generateSiteScript(
      { ...project, reactComponents: [] },
      issues,
      getPageHref
    ),
  });
  files.push({ path: 'src/styles/site.css', content: generateSiteCss(project, resolveAssetUrlFrom('/')) });

  // React components of the website.
  project.reactComponents.forEach(component => {
    const { code, errors } = preprocessReactCode(component.code);
    errors.forEach(error =>
      issues.push({ severity: 'error', source: `React component "${component.name}"`, message: error.message, line: error.line })
    );
    files.push({
      path: `src/components/${component.name}.jsx`,
      content: `${REACT_IMPORT}\n\n${code.trim()}\n\nexport default ${component.name};\n`,
    });
  });

  const faviconUrl = project.settings.faviconAssetId ? resolveAssetUrlFrom('')(project.settings.faviconAssetId) : null;
  const googleFontsUrl = getGoogleFontsUrl(project);

  project.pages.forEach(page => {
    const baseName = getPageFileName(page).replace(/\.html$/, '');
    const componentName = toComponentName(page.name) + 'Page';
    const context = createRenderContext(project, { mode: 'export', resolveAssetUrl: resolveAssetUrlFrom(''), getPageHref });
    const html = renderTree(page.root, context);
    const usedComponents = new Set();
    let jsx;
    try {
      jsx = htmlToJsx(html, usedComponents, 2);
    } catch (error) {
      issues.push({ severity: 'error', source: `Page "${page.name}"`, message: 'Unable to convert the page to JSX: ' + error.message });
      jsx = '    <div />';
    }
    const imports = Array.from(usedComponents)
      .map(name => `import ${name} from '../components/${name}.jsx';`)
      .join('\n');
    files.push({
      path: `src/pages/${componentName}.jsx`,
      content: `// The page "${page.name}", generated by Webvelop.\nimport React from 'react';\n${imports}${imports ? '\n' : ''}\nexport default function ${componentName}() {\n  return (\n${jsx}\n  );\n}\n`,
    });
    const pageConfig = generatePageScript(project, page, context, issues, 'export').replace(
      /\nWebvelop\.start\([^)]*\);$/,
      ''
    );
    files.push({ path: `src/webvelop/page-${baseName}.config.js`, content: pageConfig });
    files.push({
      path: `src/styles/page-${baseName}.css`,
      content: generateTreeCss(page.root, resolveAssetUrlFrom('/'), page.css),
    });
    files.push({
      path: `src/entries/${baseName}.jsx`,
      content: `import './../webvelop/react-global.js';
import React, { useEffect } from 'react';
import { createRoot } from 'react-dom/client';
import '../webvelop/webvelop.css';
import '../styles/site.css';
import '../styles/page-${baseName}.css';
import '../webvelop/webvelop-runtime.js';
import '../webvelop/site-config.js';
import '../webvelop/page-${baseName}.config.js';
import ${componentName} from '../pages/${componentName}.jsx';

function App() {
  // Start the interactions, behaviors and variables once the page is rendered.
  useEffect(() => {
    window.Webvelop.start({ mode: 'site' });
  }, []);
  return <${componentName} />;
}

createRoot(document.getElementById('root')).render(<App />);
`,
    });
    const title = page.title && page.title !== project.settings.title
      ? `${page.title} | ${project.settings.title || project.name}`
      : project.settings.title || project.name;
    files.push({
      path: getPageFileName(page),
      content: [
        '<!DOCTYPE html>',
        `<html lang="${escapeAttribute(project.settings.language || 'en')}">`,
        '  <head>',
        '    <meta charset="utf-8" />',
        '    <meta name="viewport" content="width=device-width, initial-scale=1" />',
        `    <title>${escapeHtml(title)}</title>`,
        page.description || project.settings.description
          ? `    <meta name="description" content="${escapeAttribute(page.description || project.settings.description)}" />`
          : '',
        faviconUrl ? `    <link rel="icon" href="${escapeAttribute(faviconUrl)}" />` : '',
        googleFontsUrl ? `    <link rel="stylesheet" href="${escapeAttribute(googleFontsUrl)}" />` : '',
        project.settings.headHtml ? '    ' + project.settings.headHtml : '',
        '  </head>',
        '  <body>',
        '    <div id="root"></div>',
        `    <script type="module" src="/src/entries/${baseName}.jsx"></script>`,
        '  </body>',
        '</html>',
        '',
      ]
        .filter(line => line !== '')
        .join('\n'),
    });
    pageEntries.push({ baseName, file: getPageFileName(page) });
  });

  files.push({
    path: 'vite.config.js',
    content: `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { resolve } from 'path';

// One HTML entry per page of the website.
export default defineConfig({
  plugins: [react()],
  base: './',
  build: {
    rollupOptions: {
      input: {
${pageEntries.map(entry => `        ${JSON.stringify(entry.baseName)}: resolve(__dirname, ${JSON.stringify(entry.file)}),`).join('\n')}
      },
    },
  },
});
`,
  });
  files.push({
    path: 'package.json',
    content:
      JSON.stringify(
        {
          name: packageName,
          private: true,
          version: project.version || '1.0.0',
          type: 'module',
          scripts: { dev: 'vite', build: 'vite build', preview: 'vite preview' },
          dependencies: { react: '^18.2.0', 'react-dom': '^18.2.0' },
          devDependencies: { '@vitejs/plugin-react': '^4.3.0', vite: '^5.4.0' },
        },
        null,
        2
      ) + '\n',
  });
  files.push({
    path: 'README.md',
    content: `# ${project.name}

This React project was exported from **Webvelop**.

- \`src/pages/\`: one React component per page, written in JSX.
- \`src/components/\`: the React components of the website.
- \`src/styles/\`: the styles of the website and of each page.
- \`src/webvelop/\`: the Webvelop runtime, running the interactions, behaviors and variables.
- \`public/assets/\`: images, videos, fonts and other files.

## Usage

\`\`\`bash
npm install
npm run dev     # start a development server
npm run build   # build the website in dist/
\`\`\`
`,
  });
  files.push({ path: '.gitignore', content: 'node_modules\ndist\n' });

  project.assets.forEach(asset => {
    files.push({ path: 'public/' + getAssetExportPath(project, asset.id), assetId: asset.id });
  });
  return { files, issues };
};
